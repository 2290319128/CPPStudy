/*
题目1：机器人关节角度统计
机器人运行时，某个关节在不同时刻记录了 N 个角度

输入：
4
0.1 0.2 0.3 0.4

输出：
平均关节角度: 0.25
最大关节角度: 0.4
*/

/*
- **基础练习 A**：在程序里增加 `min_angle`，同时输出最小值。
- **基础练习 B**：计算角度极差 $R=q_{\max}-q_{\min}$。
- **思考练习 C**：不使用 `vector`，仅用几个变量完成平均值、最大值统计，额外空间做到 $O(1)$。
*/

#include <iostream> // 标准输入输出库：提供 std::cin、std::cout、std::cerr
#include <vector> // 标准动态数组库：提供 std::vector

#include "console_utf8.h"

int main(){
    //setup_utf8_console(); // 自动将 Windows 终端输入、输出设为 UTF-8
    SetConsoleOutputCP(CP_UTF8); // 设置 Windows 终端输出为 UTF-8
    // ===== 第 1 步：读取采样个数 =====
    int n = 0;
    if (!(std::cin >> n) || n <= 0) {  // 如果读入失败，或者 n 小于等于 0
        std::cerr << "输入的采样个数无效，请输入一个正整数。\n" << std::endl;
        return 1; // 非正常退出
    }
    //cin >> angles[i] 本身就已经完成了"读入"，其从流里取一个值，写进 angles[i]。
    //再返回 cin 本身，用来判断成功还是失败。

    // ===== 第 2 步：创建存储关节角度的数组 =====
    // std::vector<double>：存储 double 类型元素的动态数组
    // angles(n)：数组中有 n 个元素；下标从 0 到 n-1
    std::vector<double> angles(n);

    // ===== 第 3 步：定义统计变量 =====
    double sum = 0.0;               // 存放目前已经读取的角度之和
    double max_angle = 0.0;         // 暂存最大值；第一个数据读入时会覆盖它

    // ===== 第 4 步：读取关节角度 =====
    for (int i = 0; i < n; ++i) {
        if (!(std::cin >> angles[i])) {  // 如果读入失败
            std::cerr << "错误：第 " << (i + 1) << " 个角度读取失败。\n";
            return 1; // 非正常退出
        }
        // 累加角度：sum += angles[i] 等价于 sum = sum + angles[i]
        sum += angles[i];               // 累加求和
        // 第一项必须用实际数据初始化 max_angle
        // || 表示逻辑“或”：两个条件满足任意一个即为真
        // > 表示“大于”；== 表示“是否相等”（不是赋值）
        if (i == 0 || angles[i] > max_angle) { // 更新最大值
            max_angle = angles[i];
        }
    }


    // ===== 第 5 步：计算算术平均值 =====
    double average_angle = sum / n;

    // ===== 第 6 步：输出统计结果 =====
    std::cout << "平均关节角度: " << average_angle << "\n";
    std::cout << "最大关节角度: " << max_angle << "\n";

    // ===== 第 7 步：正常退出 =====
    return 0;
}

/*
i++和++i的区别：
1. i++ 是后置递增运算符，先使用变量 i 的当前值，然后再将 i 的值加 1。
2. ++i 是前置递增运算符，先将 i 的值加 1，然后再使用变量 i 的新值。
在循环中使用 i++ 和 ++i 的效果是一样的，因为循环体内并没有使用 i 的值进行其他操作，所以在这种情况下，
选择哪一个都不会影响循环的执行结果。
*/

/*
1. cin >> 每次只取一个值，它不会一次性把整行都解析完，也不会自动帮你读 n 个。
2. 它按目标类型解析输入流中的数据，遇到空格、换行符或其他分隔符时就会停止读取。
所以空格和换行一样
cin >> n，n 是 int，它就找下一个整数。
cin >> angles[i]，angles[i] 是 double，它就找下一个浮点数。
3. 剩下的数据留在缓冲区，等待下一次读取。
4. 每个 cin >> 只解析一个对应类型的值，不解析其他值；要读多个，
就得写多次或放进循环。类型不对会失败
*/
